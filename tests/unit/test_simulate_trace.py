"""callTracer parsing, on traces captured from a real anvil (tests/fixtures/traces,
regenerated by capture.py there) and on hand-built malformed ones."""

import copy
import json
from functools import cache
from pathlib import Path
from typing import Any

import pytest
from eth_utils import to_checksum_address

from mandate_firewall.models import CallFrame, CallType
from mandate_firewall.simulate.trace import (
    MAX_CALL_DEPTH,
    TraceParseError,
    parse_call_trace,
)

FIXTURES = Path(__file__).parent.parent / "fixtures" / "traces"
A = "0x" + "aa" * 20
B = "0x" + "bb" * 20


@cache
def _load(name: str) -> dict[str, Any]:
    return json.loads((FIXTURES / f"{name}.json").read_text())


def fixture(name: str) -> dict[str, Any]:
    return copy.deepcopy(_load(name))


def cs(address: str) -> str:
    return to_checksum_address(address)


def shape(calls: tuple[CallFrame, ...]) -> list[tuple[int, str, int, bool]]:
    return [(c.depth, c.call_type.value, c.value, c.reverted) for c in calls]


def test_fixtures_come_from_the_expected_anvil() -> None:
    for name in ("nested", "selfdestruct", "create_tx", "reverted_tx", "eth_transfer"):
        assert fixture(name)["anvil"].startswith("anvil Version: 1.8.3")


def test_eth_transfer() -> None:
    f = fixture("eth_transfer")
    parsed = parse_call_trace(f["trace"])
    (frame,) = parsed.calls
    assert (frame.caller, frame.target) == (f["sender"], cs(f["recipient"]))
    assert (frame.call_type, frame.value, frame.selector, frame.reverted) == (
        CallType.CALL,
        10**15,
        None,
        False,
    )
    assert parsed.touched == (f["sender"], cs(f["recipient"]))
    assert parsed.created == ()


def test_nested_calls() -> None:
    f = fixture("nested")
    router, sink, child = cs(f["router"]), cs(f["sink"]), cs(f["child"])
    parsed = parse_call_trace(f["trace"])

    assert shape(parsed.calls) == [
        (0, "CALL", 10, False),  # the tx: 10 wei to the router
        (1, "CALL", 1, False),  # router -> sink, 1 wei
        (1, "STATICCALL", 0, False),
        (1, "DELEGATECALL", 0, False),  # anvil reports value 0xa here; nothing moves
        (1, "CALL", 0, True),  # reverter
        (1, "CALL", 0, True),  # reverter with a reason string
        (1, "CALL", 0, True),  # child, which reverts...
        (2, "CALL", 0, True),  # ...so its call to the sink is rolled back too
        (1, "CREATE", 0, False),
        (1, "CREATE2", 0, False),
        (1, "CREATE", 0, True),  # init code reverted
    ]
    top, transfer, static, delegate = parsed.calls[:4]
    assert (top.caller, top.target, top.selector) == (f["sender"], router, "0xdeadbeef")
    assert (transfer.caller, transfer.target, transfer.selector) == (router, sink, "0xa9059cbb")
    assert static.selector is None  # empty input
    assert (delegate.caller, delegate.target) == (router, sink)
    assert (parsed.calls[7].caller, parsed.calls[7].target) == (child, sink)

    create, create2, failed_create = parsed.calls[8:]
    assert create.selector is None  # input is init code, not calldata
    assert failed_create.target is None
    assert parsed.created == (create.target, create2.target)
    assert len(set(parsed.touched)) == len(parsed.touched)
    assert {f["sender"], router, sink, child, create.target, create2.target} <= set(parsed.touched)


def test_revert_reason_text_is_never_kept() -> None:
    f = fixture("nested")
    reason = f["injected_revert_reason"]
    assert reason in json.dumps(f["trace"])  # anvil does put it in the trace...
    assert reason not in parse_call_trace(f["trace"]).model_dump_json()  # ...we don't


def test_selfdestruct() -> None:
    f = fixture("selfdestruct")
    parsed = parse_call_trace(f["trace"])
    top, destruct = parsed.calls
    assert shape(parsed.calls) == [(0, "CALL", 5, False), (1, "SELFDESTRUCT", 5, False)]
    assert (destruct.caller, destruct.target) == (cs(f["destructor"]), cs(f["beneficiary"]))
    assert cs(f["beneficiary"]) in parsed.touched


def test_contract_creation_transaction() -> None:
    f = fixture("create_tx")
    parsed = parse_call_trace(f["trace"])
    assert shape(parsed.calls) == [(0, "CREATE", 3, False), (1, "CALL", 2, False)]
    created = cs(f["created"])
    assert parsed.calls[0].target == created
    assert (parsed.calls[1].caller, parsed.calls[1].target) == (created, cs(f["sink"]))
    assert parsed.created == (created,)


def test_reverted_transaction() -> None:
    f = fixture("reverted_tx")
    assert f["status"] == "0x0"
    parsed = parse_call_trace(f["trace"])
    assert shape(parsed.calls) == [(0, "CALL", 0, True), (1, "CALL", 0, True)]
    assert parsed.created == ()


def test_creates_under_a_reverted_frame_create_nothing() -> None:
    trace = {
        "type": "CALL",
        "from": A,
        "to": B,
        "error": "execution reverted",
        "calls": [{"type": "CREATE2", "from": B, "to": A, "input": "0x00"}],
    }
    parsed = parse_call_trace(trace)
    assert parsed.calls[1].reverted
    assert parsed.created == ()


def test_children_keep_their_order() -> None:
    trace = {
        "type": "CALL",
        "from": A,
        "to": B,
        "calls": [
            {"type": "CALL", "from": B, "to": A, "value": "0x1", "calls": [
                {"type": "CALL", "from": A, "to": B, "value": "0x2"},
            ]},
            {"type": "CALL", "from": B, "to": A, "value": "0x3"},
        ],
    }  # fmt: skip
    assert [c.value for c in parse_call_trace(trace).calls] == [0, 1, 2, 3]


def deep_trace(depth: int) -> dict[str, Any]:
    trace: dict[str, Any] = {"type": "CALL", "from": A, "to": B}
    for _ in range(depth):
        trace = {"type": "CALL", "from": A, "to": B, "calls": [trace]}
    return trace


def test_max_evm_depth_does_not_hit_python_recursion_limit() -> None:
    parsed = parse_call_trace(deep_trace(MAX_CALL_DEPTH))
    assert len(parsed.calls) == MAX_CALL_DEPTH + 1
    assert parsed.calls[-1].depth == MAX_CALL_DEPTH
    with pytest.raises(TraceParseError, match="depth"):
        parse_call_trace(deep_trace(MAX_CALL_DEPTH + 1))


def mutate(path: list[Any], value: Any) -> dict[str, Any]:
    """The nested fixture with one field set (or deleted, for ...)."""
    trace = fixture("nested")["trace"]
    node = trace
    for key in path[:-1]:
        node = node[key]
    if value is ...:
        del node[path[-1]]
    else:
        node[path[-1]] = value
    return trace


@pytest.mark.parametrize(
    ("path", "value"),
    [
        pytest.param(["type"], "DELEGATECALL", id="tx as delegatecall"),
        pytest.param(["type"], "SELFDESTRUCT", id="tx as selfdestruct"),
        pytest.param(["type"], "AUTHCALL", id="unknown type"),
        pytest.param(["type"], "call", id="lowercase type"),
        pytest.param(["type"], ["CALL"], id="unhashable type"),
        pytest.param(["type"], ..., id="no type"),
        pytest.param(["from"], ..., id="no from"),
        pytest.param(["from"], "0x1234", id="short from"),
        pytest.param(["to"], ..., id="no to"),
        pytest.param(["calls", 0, "to"], None, id="call without target"),
        pytest.param(["calls", 7, "to"], ..., id="successful create without target"),
        pytest.param(["value"], 10, id="value not hex"),
        pytest.param(["value"], "0x0a", id="value leading zero"),
        pytest.param(["calls", 1, "value"], "0x1", id="staticcall with value"),
        pytest.param(["input"], "0xabc", id="odd input"),
        pytest.param(["input"], None, id="null input"),
        pytest.param(["calls"], {}, id="calls not a list"),
        pytest.param(["calls", 0], "CALL", id="frame not an object"),
    ],
)
def test_malformed_traces_raise(path: list[Any], value: Any) -> None:
    with pytest.raises(TraceParseError):
        parse_call_trace(mutate(path, value))


@pytest.mark.parametrize("trace", [None, [], "0x", 1])
def test_non_object_trace_raises(trace: Any) -> None:
    with pytest.raises(TraceParseError):
        parse_call_trace(trace)


def test_selfdestruct_with_subcalls_raises() -> None:
    trace = fixture("selfdestruct")["trace"]
    trace["calls"][0]["calls"] = [{"type": "CALL", "from": A, "to": B}]
    with pytest.raises(TraceParseError, match="SELFDESTRUCT"):
        parse_call_trace(trace)


